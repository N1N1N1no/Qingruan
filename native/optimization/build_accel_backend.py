"""Generate explicit wiring for mutually exclusive engines and one PE array.

The generated RTL has no behavioral memory or simulation-only computation.
All AXI responses are granted only to the engine that owns the command.
"""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parent
parser=argparse.ArgumentParser()
parser.add_argument('--with-softmax',action='store_true',help='write a separate experimental opcode-5 backend; retain the default backend')
parser.add_argument('--with-layernorm',action='store_true',help='write a separate experimental opcode-5/6 Softmax/LayerNorm backend')
parser.add_argument('--with-vector',action='store_true',help='also include opcode-7 vector DMA')
parser.add_argument('--with-reorder',action='store_true',help='include all engines through opcode8 and a four-bit owner')
parser.add_argument('--shared-fp32',action='store_true',help='pool one FP32 ALU across the enabled FP engines')
options=parser.parse_args()
if options.with_reorder:options.with_vector=True
if options.with_vector:options.with_layernorm=True
if options.with_layernorm:options.with_softmax=True
assert not options.shared_fp32 or options.with_softmax,'enable an FP engine before pooling its arithmetic'
fields = [('awaddr', '31:0'), ('awid', 'ID_WIDTH-1:0'), ('awlen', '7:0'), ('awsize', '2:0'), ('awburst', '1:0'), ('awvalid', ''), ('awready', ''),
    ('wdata', '63:0'), ('wstrb', '7:0'), ('wlast', ''), ('wvalid', ''), ('wready', ''), ('bid', 'ID_WIDTH-1:0'), ('bresp', '1:0'), ('bvalid', ''), ('bready', ''),
    ('araddr', '31:0'), ('arid', 'ID_WIDTH-1:0'), ('arlen', '7:0'), ('arsize', '2:0'), ('arburst', '1:0'), ('arvalid', ''), ('arready', ''),
    ('rdata', '63:0'), ('rid', 'ID_WIDTH-1:0'), ('rresp', '1:0'), ('rlast', ''), ('rvalid', ''), ('rready', '')]
inputs = {'awready', 'wready', 'bid', 'bresp', 'bvalid', 'arready', 'rdata', 'rid', 'rresp', 'rlast', 'rvalid'}
gated = {'awready', 'wready', 'bvalid', 'arready', 'rvalid'}
engines=[('copy',1,'axi_dma_copy'),('gelu',2,'axi_gelu_engine'),('gemm',3,'axi_affine_gemm'),('quant',4,'axi_quant_engine')]
if options.with_softmax:engines.append(('softmax',5,'axi_softmax_engine'))
if options.with_layernorm:engines.append(('layernorm',6,'axi_layernorm_engine'))
if options.with_vector:engines.append(('vector',7,'axi_vector_engine'))
if options.with_reorder:engines.append(('reorder',8,'axi_reorder_engine'))
def inst(module, name, connections, params=''):
    return module + ' ' + params + ' ' + name + '(\n ' + ',\n '.join('.%s(%s)' % p for p in connections) + '\n);'

ports = ['input wire clk,rst_n', 'input wire request_valid,output wire request_ready',
    'input wire[7:0]request_opcode,input wire[511:0]request_arguments', 'input wire cancel,output wire engine_busy,engine_done',
    'output wire[7:0]engine_error', 'output wire[31:0]engine_cycles,engine_bytes']
for f, width in fields:
    ports.append(('input' if f in inputs else 'output') + ' wire ' + ('[' + width + ']' if width else '') + 'm_axi_' + f)
lines = ['// Generated by build_accel_backend.py; one owner, one physical PE SRAM array.',
    'module axi_accel_backend #(parameter ROWS=8,COLS=32,LANES=4,ID_WIDTH=3,BANKS=ROWS*COLS)(', ',\n'.join(ports), ');',
    'reg[2:0]owner;', 'wire copy_ready,gelu_ready,gemm_ready,quant_ready;', 'wire[511:0]args=request_arguments;', 'wire start=request_valid&&request_ready;',
    'assign request_ready=owner==0&&copy_ready&&gelu_ready&&gemm_ready&&quant_ready&&request_opcode>=1&&request_opcode<=4;',
    'assign engine_busy=owner!=0;',
    'always@(posedge clk or negedge rst_n)begin', ' if(!rst_n)owner<=0;',
    ' else if(start)owner<=request_opcode[2:0];else if(engine_done)owner<=0;', 'end',
    'wire[BANKS*4-1:0]gemm_bank_addr;wire[BANKS-1:0]gemm_bank_ce,gemm_bank_we;wire[BANKS*8-1:0]gemm_bank_write;',
    'wire[BANKS*4-1:0]gelu_bank_addr;wire[BANKS-1:0]gelu_bank_ce,gelu_bank_we;wire[BANKS*8-1:0]gelu_bank_write;',
    'wire[BANKS*8-1:0]bank_read;',
    'wire tile_valid,dot_valid;wire[ROWS*LANES*8-1:0]a_raw;wire[7:0]a_zero;wire[COLS*8-1:0]b_zero;wire[COLS*LANES*32-1:0]dot_out;',
    'generate if(BANKS<128||ROWS<4||COLS<8)begin:UNSUPPORTED_CONFIG',
    ' ERROR_BACKEND_REQUIRES_AT_LEAST_128_BANKS_4_ROWS_8_COLUMNS invalid_config();end endgenerate']
if options.with_softmax:
    lines=[line.replace('quant_ready;', 'quant_ready,softmax_ready;').replace('&&request_opcode>=1&&request_opcode<=4;', '&&softmax_ready&&request_opcode>=1&&request_opcode<=5;')for line in lines]
    lines += ['wire[BANKS*4-1:0]softmax_bank_addr;wire[BANKS-1:0]softmax_bank_ce,softmax_bank_we;wire[BANKS*8-1:0]softmax_bank_write;']
if options.with_layernorm:
    lines=[line.replace('quant_ready,softmax_ready;', 'quant_ready,softmax_ready,layernorm_ready;').replace('&&request_opcode<=5;', '&&layernorm_ready&&request_opcode<=6;')for line in lines]
    lines += ['wire[BANKS*4-1:0]layernorm_bank_addr;wire[BANKS-1:0]layernorm_bank_ce,layernorm_bank_we;wire[BANKS*8-1:0]layernorm_bank_write;']
if options.with_vector:
    lines=[line.replace('softmax_ready,layernorm_ready;', 'softmax_ready,layernorm_ready,vector_ready;').replace('&&request_opcode<=6;', '&&vector_ready&&request_opcode<=7;')for line in lines]
    lines += ['wire[BANKS*4-1:0]vector_bank_addr;wire[BANKS-1:0]vector_bank_ce,vector_bank_we;wire[BANKS*8-1:0]vector_bank_write;']
if options.with_reorder:
    lines=[line.replace('layernorm_ready,vector_ready;', 'layernorm_ready,vector_ready,reorder_ready;').replace('&&request_opcode<=7;', '&&reorder_ready&&request_opcode<=8;').replace('reg[2:0]owner;', 'reg[3:0]owner;').replace('owner<=request_opcode[2:0]', 'owner<=request_opcode[3:0]')for line in lines]
fp_engines=[(tag,code)for tag,code,_ in engines if tag in ['softmax','layernorm','vector']]
if options.shared_fp32:
    lines += ['wire fp_ready,fp_valid,fp_out_ready;wire[31:0]fp_result;wire[4:0]fp_flags;']
    for tag,_ in fp_engines:
        lines += ['wire '+tag+'_shared_alu_valid,'+tag+'_shared_alu_ready,'+tag+'_shared_alu_out_valid,'+tag+'_shared_alu_out_ready;',
            'wire[3:0]'+tag+'_shared_alu_op;wire[31:0]'+tag+'_shared_alu_a,'+tag+'_shared_alu_b,'+tag+'_shared_alu_result;wire[4:0]'+tag+'_shared_alu_flags;']
    def fp_select(field):
        zero="1'b0"if field in ['valid','out_ready']else"4'b0"if field=='op'else"32'b0"
        return ''.join('owner==%d?%s_shared_alu_%s:'%(code,tag,field)for tag,code in fp_engines)+zero
    fp_connections=[('clk','clk'),('rst_n','rst_n'),('in_valid',fp_select('valid')),('in_ready','fp_ready'),('op',fp_select('op')),('a',fp_select('a')),('b',fp_select('b')),
        ('out_valid','fp_valid'),('out_ready','fp_out_ready'),('result','fp_result'),('flags','fp_flags')]
    lines += ['assign fp_out_ready='+fp_select('out_ready')+';',inst('fp32_alu','u_shared_fp32',fp_connections)]
    for tag,code in fp_engines:
        lines += ['assign '+tag+'_shared_alu_ready=owner==%d&&fp_ready;'%code,
            'assign '+tag+'_shared_alu_out_valid=owner==%d&&fp_valid;'%code,
            'assign '+tag+'_shared_alu_result=fp_result;assign '+tag+'_shared_alu_flags=fp_flags;']
for tag,_,_ in engines:
    lines += ['wire ' + tag + '_busy,' + tag + '_done;', 'wire[7:0]' + tag + '_error;', 'wire[31:0]' + tag + '_cycles,' + tag + '_bytes;']
    for f, width in fields:
        if f not in inputs:
            lines.append('wire ' + ('[' + width + ']' if width else '') + tag + '_' + f + ';')
for name in ['done', 'error', 'cycles', 'bytes']:
    lines.append('assign engine_'+name+'='+''.join('owner==%d?%s_%s:'%(code,tag,name) for tag,code,_ in engines)+'0;')
for f, _ in fields:
    if f not in inputs:
        lines.append('assign m_axi_'+f+'='+''.join('owner==%d?%s_%s:'%(code,tag,f) for tag,code,_ in engines)+'0;')
for tag, opcode, module in engines:
    con = [('clk', 'clk'), ('rst_n', 'rst_n'), ('cmd_valid', 'start&&request_opcode==8\'d%d' % opcode), ('cmd_ready', tag + '_ready'),
        ('cancel', 'cancel&&owner==%d' % opcode), ('busy', tag + '_busy'), ('done', tag + '_done'), ('error', tag + '_error'), ('cycles', tag + '_cycles'),
        ('output_bytes' if tag == 'gemm' else 'streamed_bytes', tag + '_bytes')]
    if tag == 'copy':
        names = ['source', 'destination', 'row_bytes', 'rows', 'source_stride', 'destination_stride']
    elif tag == 'gelu':
        names = ['source', 'destination', 'table', 'channels', 'rows']
    elif tag == 'quant':
        names = ['source', 'destination', 'table', 'elements']
    elif tag == 'softmax':
        names = ['source', 'destination', 'channels', 'rows', 'source_stride', 'destination_stride']
    elif tag == 'layernorm':
        names = ['source', 'destination', 'scale', 'bias', 'elements', 'rows', 'source_stride', 'destination_stride', 'epsilon']
    elif tag == 'vector':
        names = ['a','b','c','destination','elements','rows','a_stride','b_stride','c_stride','destination_stride','operation','flags','zero','scalar_b','scalar_c','scalar_d']
    elif tag == 'reorder':
        names = ['source','destination','row_bytes','rank']
    else:
        names = ['a', 'b', 'c', 'm', 'n', 'k']
    con += [('cmd_' + name, 'args[%d*32+:32]' % i) for i, name in enumerate(names)]
    if tag=='reorder':con += [('cmd_dimensions','args[4*32+:128]'),('cmd_source_strides','args[8*32+:128]')]
    if tag == 'gemm':
        con += [('cmd_a_zero', 'args[6*32+:8]'), ('cmd_b_zero', 'args[7*32+:8]'), ('cmd_trans_b', 'args[8*32]')]
        con += [(k, k) for k in ['tile_valid', 'a_raw', 'a_zero', 'b_zero', 'dot_valid', 'dot_out']]
    if tag in ['gelu','gemm','softmax','layernorm','vector']:
        con += [(k, tag + '_' + k) for k in ['bank_addr', 'bank_ce', 'bank_we', 'bank_write']]
    if tag in ['gelu','softmax','layernorm','vector']:
        con += [('bank_read', 'bank_read')]
    for f, _ in fields:
        expression = 'm_axi_' + f if f in inputs else tag + '_' + f
        if f in gated:
            expression += '&&owner==%d' % opcode
        con.append(('m_axi_' + f, expression))
    params = '#(.ID_WIDTH(ID_WIDTH))' if tag != 'gemm' else '#(.ROWS(ROWS),.COLS(COLS),.LANES(LANES),.ID_WIDTH(ID_WIDTH))'
    if tag in ['gelu','softmax','layernorm','vector']:params='#(.ID_WIDTH(ID_WIDTH),.BANKS(BANKS))'
    if options.shared_fp32 and tag in ['softmax','layernorm','vector']:
        params=params[:-1]+',.SHARED_ALU(1))'
        con += [(field,tag+'_'+field)for field in['shared_alu_valid','shared_alu_ready','shared_alu_op','shared_alu_a','shared_alu_b','shared_alu_out_valid','shared_alu_out_ready','shared_alu_result','shared_alu_flags']]
    lines.append(inst(module, 'u_' + tag, con, params))
con = [('clk', 'clk'), ('rst_n', 'rst_n'), ('tile_valid', 'tile_valid&&owner==3')]
con += [(k, k) for k in ['a_raw', 'a_zero', 'b_zero', 'dot_valid', 'dot_out', 'bank_read']]
for k in ['bank_addr', 'bank_ce', 'bank_we', 'bank_write']:
    con.append((k, 'owner==3?gemm_' + k + ':owner==2?gelu_' + k + (':owner==5?softmax_'+k if options.with_softmax else '') + (':owner==6?layernorm_'+k if options.with_layernorm else '') + (':owner==7?vector_'+k if options.with_vector else '') + ':0'))
lines.append(inst('affine_array', 'u_array', con, '#(.ROWS(ROWS),.COLS(COLS),.LANES(LANES))'))
lines.append('endmodule')
path = ROOT / ('rtl/axi_accel_shared_backend.sv' if options.shared_fp32 else 'rtl/axi_accel_complete_backend.sv' if options.with_reorder else 'rtl/axi_accel_vector_backend.sv' if options.with_vector else 'rtl/axi_accel_layernorm_backend.sv' if options.with_layernorm else 'rtl/axi_accel_softmax_backend.sv' if options.with_softmax else 'rtl/axi_accel_backend.sv')
path.write_text('\n'.join(lines) + '\n')
print('ACCEL_BACKEND_GENERATED', path, flush=True)
