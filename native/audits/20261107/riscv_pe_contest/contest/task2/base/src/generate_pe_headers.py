def flatten_conv_weight(weight_hw):
    """
    PyTorch Conv weight:

        [OC, IC, KH, KW]

    Flatten to:

        [OC, K]

    where:

        K = IC * KH * KW

    Ordering:

        k =
            ic * (KH * KW)
            + kh * KW
            + kw

    This is exactly the ordering already used by our
    Conv1 / Conv2 software-hardware flow.
    """

    if weight_hw.ndim != 4:
        raise ValueError(
            f"Expected Conv weight ndim=4, "
            f"got shape={weight_hw.shape}"
        )

    oc, ic, kh, kw = weight_hw.shape

    return weight_hw.reshape(
        oc,
        ic * kh * kw
    )


def flatten_fc_weight(weight_hw):
    """
    PyTorch Linear weight:

        [OUT_FEATURES, IN_FEATURES]

    PE logical format:

        [OC, K]

    Therefore no permutation is required.
    """

    if weight_hw.ndim != 2:
        raise ValueError(
            f"Expected FC weight ndim=2, "
            f"got shape={weight_hw.shape}"
        )

    return weight_hw.copy()


def write_u8_2d_array(
    f,
    name,
    array,
    values_per_line=16
):
    """
    Write:

        static const uint8_t name[ROWS][COLS] = {...};

    Values are emitted as hexadecimal bytes.
    """

    rows, cols = array.shape

    f.write(
        f"static const uint8_t "
        f"{name}[{rows}][{cols}] = {{\n"
    )

    for r in range(rows):

        f.write("    {\n")

        row = array[r]

        for start in range(
            0,
            cols,
            values_per_line
        ):

            end = min(
                start + values_per_line,
                cols
            )

            values = []

            for value in row[start:end]:

                values.append(
                    f"0x{int(value):02x}"
                )

            f.write(
                "        "
                + ", ".join(values)
            )

            if end < cols:
                f.write(",")

            f.write("\n")

        f.write("    }")

        if r != rows - 1:
            f.write(",")

        f.write("\n")

    f.write("};\n\n")


def write_i32_array(
    f,
    name,
    array,
    values_per_line=8
):
    """
    Write INT32 bias array.
    """

    size = array.shape[0]

    f.write(
        f"static const int32_t "
        f"{name}[{size}] = {{\n"
    )

    for start in range(
        0,
        size,
        values_per_line
    ):

        end = min(
            start + values_per_line,
            size
        )

        values = [
            str(int(v))
            for v in array[start:end]
        ]

        f.write(
            "    "
            + ", ".join(values)
        )

        if end < size:
            f.write(",")

        f.write("\n")

    f.write("};\n\n")


def generate_header(
    output_path,
    guard,
    prefix,
    weight_hw,
    bias_q,
    layer_type
):
    """
    Generate one PE target-data header.

    Logical weight format:

        weight_hw[OC][K]

    C later accesses:

        k = k_pass * 16 + pe_row

        weight =
            weight_hw[output_channel][k]
    """

    if layer_type == "conv":

        weight_flat = flatten_conv_weight(
            weight_hw
        )

    elif layer_type == "fc":

        weight_flat = flatten_fc_weight(
            weight_hw
        )

    else:

        raise ValueError(
            f"Unknown layer type: "
            f"{layer_type}"
        )

    oc = weight_flat.shape[0]
    k_total = weight_flat.shape[1]

    k_passes = (
        k_total + PE_K_PER_PASS - 1
    ) // PE_K_PER_PASS

    oc_tiles = (
        oc + PE_NUM_COLS - 1
    ) // PE_NUM_COLS

    prefix_upper = prefix.upper()

    with open(
        output_path,
        "w"
    ) as f:

        f.write(
            "/*\n"
        )

        f.write(
            " * Auto-generated by "
            "generate_pe_headers.py\n"
        )

        f.write(
            " *\n"
        )

        f.write(
            f" * Layer       : {prefix}\n"
        )

        f.write(
            f" * Output count: {oc}\n"
        )

        f.write(
            f" * K total     : {k_total}\n"
        )

        f.write(
            f" * K/pass      : {PE_K_PER_PASS}\n"
        )

        f.write(
            f" * K passes    : {k_passes}\n"
        )

        f.write(
            f" * OC tiles    : {oc_tiles}\n"
        )

        f.write(
            " *\n"
        )

        f.write(
            " * Weight layout:\n"
        )

        f.write(
            f" *     {prefix}_weight_hw"
            "[output_channel][k]\n"
        )

        f.write(
            " *\n"
        )

        f.write(
            " * For convolution:\n"
        )

        f.write(
            " *     k = "
            "input_channel * 9 "
            "+ kh * 3 + kw\n"
        )

        f.write(
            " *\n"
        )

        f.write(
            " * PE scheduling:\n"
        )

        f.write(
            " *     k = "
            "k_pass * 16 + pe_row\n"
        )

        f.write(
            " */\n\n"
        )

        f.write(
            f"#ifndef {guard}\n"
        )

        f.write(
            f"#define {guard}\n\n"
        )

        f.write(
            "#include <stdint.h>\n\n"
        )

        # ----------------------------------------------------
        # Layer constants
        # ----------------------------------------------------

        f.write(
            f"#define {prefix_upper}_OUT_CHANNELS "
            f"{oc}\n"
        )

        f.write(
            f"#define {prefix_upper}_K_TOTAL "
            f"{k_total}\n"
        )

        f.write(
            f"#define {prefix_upper}_K_PASSES "
            f"{k_passes}\n"
        )

        f.write(
            f"#define {prefix_upper}_OC_TILES "
            f"{oc_tiles}\n\n"
        )

        # ----------------------------------------------------
        # Weights
        # ----------------------------------------------------

        write_u8_2d_array(
            f,
            f"{prefix}_weight_hw",
            weight_flat
        )

        # ----------------------------------------------------
        # Bias
        # ----------------------------------------------------

        write_i32_array(
            f,
            f"{prefix}_bias_q",
            bias_q
        )

        f.write(
            f"#endif /* {guard} */\n"
        )

    return {
        "oc": oc,
        "k_total": k_total,
        "k_passes": k_passes,
        "oc_tiles": oc_tiles,
        "weight_bytes": weight_flat.size,
        "bias_bytes": bias_q.size * 4,
    }


